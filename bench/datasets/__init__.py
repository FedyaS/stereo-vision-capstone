def synth_sample_dirs(folder: str | Path, split: str | None = None) -> list[Path]:
    """Every sample directory of a generated dataset, in a stable order.

    Handles both layouts a generated set can have: flat (``<root>/00000``)
    and split (``<root>/train/00000``). ``split`` restricts to one subset;
    without it a split dataset yields all of them, ordered by split name then
    index, so a run over the whole set is reproducible.
    """
    folder = Path(folder)
    if not folder.is_dir():
        return []
    flat = sorted(
        d for d in folder.iterdir() if d.is_dir() and (d / "im0.png").exists()
    )
    if flat and split is None:
        return flat

    out: list[Path] = []
    for sub in sorted(d for d in folder.iterdir() if d.is_dir()):
        if split is not None and sub.name != split:
            continue
        out.extend(
            sorted(
                d for d in sub.iterdir() if d.is_dir() and (d / "im0.png").exists()
            )
        )
    return out


def synth_splits(folder: str | Path) -> list[str]:
    """Names of the splits in a generated dataset; empty when it is flat."""
    folder = Path(folder)
    if not folder.is_dir():
        return []
    return sorted(
        d.name for d in folder.iterdir()
        if d.is_dir()
        and not (d / "im0.png").exists()
        and any(c.is_dir() and (c / "im0.png").exists() for c in d.iterdir())
    )


def load_synth_dataset(
    folder: str | Path, limit: int | None = None, split: str | None = None
) -> list[StereoPair]:
    """Load every sample of a dataset written by :mod:`bench.synth`.

    A generated dataset is a folder of numbered sample directories -- possibly
    grouped into splits -- plus a ``manifest.json``. Each sample is in the
    Middlebury layout, so this is just :func:`load_image_pair` over those
    directories, which is the whole point of writing them that way.
    """
    folder = Path(folder)
    samples = synth_sample_dirs(folder, split)
    if limit:
        samples = samples[:limit]
    return [
        load_image_pair(
            d,
            name=f"{folder.name}/{d.relative_to(folder).as_posix()}",
        )
        for d in samples
    ]


def is_synth_dataset(folder: str | Path) -> bool:
    """True if ``folder`` is a generated dataset rather than a single pair.

    Checked by structure, not only by the manifest, so that pointing the
    harness at one *split* of a generated set (``.../train``) works as
    naturally as pointing it at the whole thing.
    """
    folder = Path(folder)
    if not folder.is_dir():
        return False
    if (folder / "im0.png").exists():
        return False  # a single pair, e.g. practice/
    return bool(synth_sample_dirs(folder))


def resolve_pairs(spec: str, limit: int | None = None) -> list[StereoPair]:
    """Turn a dataset spec string into concrete stereo pairs.

    Accepted specs::

        middlebury                  all MiddEval3 trainingQ scenes with GT
        middlebury:Teddy,Piano      named scenes only
        synthetic                   warp-based generated pair, exact GT
        synthetic:3                 three generated pairs with varied content
        synth:room                  one ray-traced 3-D scene, exact GT
        synth:corridor:8            eight of them, varied by seed
        synth:room:4:hard           ...at a named difficulty
        path/to/dir                 a folder with im0.png / im1.png, or a
                                    dataset generated by `bench synth`
                                    (or one split of one: .../train)

    Pairs are returned in a stable order so repeated runs are comparable.
    """
    spec = spec.strip()
    name, _, arg = spec.partition(":")

    if name == "middlebury":
        scenes = [s for s in arg.split(",") if s] or None
        pairs = [load_middlebury_scene(s) for s in (scenes or list_middlebury_scenes())]
    elif name == "synthetic":
        n = int(arg) if arg else 1
        pairs = [make_synthetic_pair(seed=i) for i in range(n)]
    elif name == "synth":
        from ..synth import generate_pair, preset

        parts = [p for p in arg.split(":") if p]
        env = parts[0] if parts else "room"
        count = int(parts[1]) if len(parts) > 1 else 1
        rules = preset(env)
        if len(parts) > 2:
            rules = rules.with_difficulty(parts[2])
        pairs = [generate_pair(rules, seed=i) for i in range(count)]
    elif is_synth_dataset(spec):
        pairs = load_synth_dataset(spec, limit)
    else:
        pairs = [load_image_pair(spec)]

    return pairs[:limit] if limit else pairs
